# 1. Crée une variable age qui vaut 17.
# 2. Affiche le résultat de la comparaison : age est-il égal à 18 ?
# 3. Ajoute 1 à age (age prend la valeur age + 1).
# 4. Affiche à nouveau la comparaison : age est-il égal à 18 ?
